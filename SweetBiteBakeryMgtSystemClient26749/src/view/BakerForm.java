    private void savebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebtnActionPerformed
         try{

        if(bakeridtxt.getText().isEmpty()
                || fullnametxt.getText().isEmpty()
                || phonetxt.getText().isEmpty()
                || specializationtxt.getText().isEmpty()){

            JOptionPane.showMessageDialog(this, "Fill all fields");

        }else{
            
            //validations 
            
             if(!bakeridtxt.getText().matches("[0-9]+")){
        JOptionPane.showMessageDialog(this, "Baker ID must be numbers only");
               
        return;
    }

    if(!fullnametxt.getText().matches("[A-Za-z ]+")){
        JOptionPane.showMessageDialog(this, "Full Name must contain letters only");
               
        return;
    }

    if(!phonetxt.getText().matches("[0-9]+")){
        JOptionPane.showMessageDialog(this,"Phone must contain digits only");
                
        return;
    }

    if(phonetxt.getText().length() != 10){
        JOptionPane.showMessageDialog(this,"Phone must be 10 digits");
                
        return;
    }

    if(!specializationtxt.getText().matches("[A-Za-z ]+")){
        JOptionPane.showMessageDialog(this, "Specialization must contain letters only");
               
        return;
    }

            Baker baker = new Baker();

            baker.setBakerId(Integer.parseInt(bakeridtxt.getText()));
            baker.setFullName(fullnametxt.getText());
            baker.setPhone(phonetxt.getText());
            baker.setSpecialization(specializationtxt.getText());

            Registry reg = LocateRegistry.getRegistry("127.0.0.1", 5004);
            BakerService service = (BakerService) reg.lookup("baker");

            Baker saved = service.registerBaker(baker);

            if(saved != null){
                JOptionPane.showMessageDialog(this, "Baker Saved Successfully");
                displayBakers();
                clearFields();
            }else{
                JOptionPane.showMessageDialog(this, "Baker Not Saved");
            }
        }

    }catch(Exception ex){
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
    }
    }//GEN-LAST:event_savebtnActionPerformed

