    private void displayBakers(){

    try{
        Registry reg = LocateRegistry.getRegistry("127.0.0.1", 5004);

        BakerService service =
        (BakerService) reg.lookup("baker");

        List<Baker> bakers = service.findAllBakers();

        DefaultTableModel model =
        (DefaultTableModel) bakerTable.getModel();

        model.setRowCount(0);

        for(Baker baker : bakers){

            Object row[] = {
                baker.getBakerId(),
                baker.getFullName(),
                baker.getPhone(),
                baker.getSpecialization()
            };

            model.addRow(row);
        }

    }catch(Exception ex){
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Table Error: " + ex.getMessage());
    }
}

