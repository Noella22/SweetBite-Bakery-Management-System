    private void sendotpbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sendotpbtnActionPerformed
            try{

        String username = usernametxt.getText();
        String password = String.valueOf(passwordtxt.getPassword());

        if(username.isEmpty() || password.isEmpty()){

            JOptionPane.showMessageDialog(this,
                    "Enter Username and Password First");

            return;
        }

        Registry reg =
                LocateRegistry.getRegistry("127.0.0.1",5004);

        UserService service =
                (UserService) reg.lookup("user");

        User user = new User();

        user.setUsername(username);
        user.setPassword(password);

        User found = service.login(user);

        if(found != null){

            Random rand = new Random();

            generatedOtp =
                    1000 + rand.nextInt(9000);

            JOptionPane.showMessageDialog(this,
                    "OTP sent to: "
                    + found.getEmail()
                    + "\nOTP: "
                    + generatedOtp);

        }else{

            JOptionPane.showMessageDialog(this,
                    "Invalid Username or Password");
        }

    }catch(Exception ex){

        ex.printStackTrace();
    }

    }//GEN-LAST:event_sendotpbtnActionPerformed

