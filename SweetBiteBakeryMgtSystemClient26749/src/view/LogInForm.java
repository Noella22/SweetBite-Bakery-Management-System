    private void loginbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginbtnActionPerformed
        try {

    String username = usernametxt.getText();
    String password = String.valueOf(passwordtxt.getPassword());

    if(username.isEmpty() || password.isEmpty()){

        JOptionPane.showMessageDialog(this,
                "Fill all fields");

    }else{

        Registry reg = LocateRegistry.getRegistry("127.0.0.1", 5004);

        UserService service = (UserService) reg.lookup("user");

        User user = new User();

        user.setUsername(username);
        user.setPassword(password);

        User found = service.login(user);

        if(found != null){

            if(otptxt.getText().isEmpty()){
        JOptionPane.showMessageDialog(this,
                "Enter OTP");
        return;
    }

    if(!otptxt.getText().equals(String.valueOf(generatedOtp))){
        JOptionPane.showMessageDialog(this,
                "Invalid OTP");
        return;
    }

    JOptionPane.showMessageDialog(this,
            "Login Successfully");

    DashboardForm dash = new DashboardForm();
    dash.setVisible(true);

    this.dispose();

}else{
            JOptionPane.showMessageDialog(this,
                    "Invalid Username or Password");
        }
    }

} catch (Exception ex) {

    ex.printStackTrace();
}
    }//GEN-LAST:event_loginbtnActionPerformed

