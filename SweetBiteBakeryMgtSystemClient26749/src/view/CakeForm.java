     private void addTableHeader(){

    DefaultTableModel model = (DefaultTableModel) cakeTable.getModel();

    Object[] columns = {
        "Cake ID",
        "Cake Name",
        "Flavor",
        "Size",
        "Price"
    };

    model.setColumnIdentifiers(columns);
}

private void displayCakes(){

    try{
        Registry reg = LocateRegistry.getRegistry("127.0.0.1", 5004);

        CakeService service =
        (CakeService) reg.lookup("cake");

        List<Cake> cakes = service.findAllCakes();

        DefaultTableModel model =
        (DefaultTableModel) cakeTable.getModel();

        model.setRowCount(0);

        for(Cake cake : cakes){

            Object row[] = {
                cake.getCakeId(),
                cake.getCakeName(),
                cake.getFlavor(),
                cake.getSize(),
                cake.getPrice()
            };

            model.addRow(row);
        }

    }catch(Exception ex){
        ex.printStackTrace();
    }
}

