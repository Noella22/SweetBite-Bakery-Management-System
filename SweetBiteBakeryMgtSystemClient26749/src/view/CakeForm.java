    private void savebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebtnActionPerformed
         try{

        if(cakeidtxt.getText().isEmpty()
                || cakenametxt.getText().isEmpty()
                || flavortxt.getText().isEmpty()
                || sizetxt.getText().isEmpty()
                || pricetxt.getText().isEmpty()){

            JOptionPane.showMessageDialog(this, "Fill all fields");

        }else{
            
            //validations
            
                if(!cakeidtxt.getText().matches("[0-9]+")){
        JOptionPane.showMessageDialog(this,"Cake ID must be numbers only");
                
        return;
    }

    if(!cakenametxt.getText().matches("[A-Za-z ]+")){
        JOptionPane.showMessageDialog(this,"Cake Name must contain letters only");
                
        return;
    }

    if(!flavortxt.getText().matches("[A-Za-z ]+")){
        JOptionPane.showMessageDialog(this,"Flavor must contain letters only");
                
        return;
    }

    if(!pricetxt.getText().matches("[0-9.]+")){
        JOptionPane.showMessageDialog(this,"Price must be numeric");
                
        return;
    }

    double price = Double.parseDouble(pricetxt.getText());

    if(price < 1000){
        JOptionPane.showMessageDialog(this,"Cake price must be at least 1000 RWF");
                
        return;
    }


            Cake cake = new Cake();

            cake.setCakeId(Integer.parseInt(cakeidtxt.getText()));
            cake.setCakeName(cakenametxt.getText());
            cake.setFlavor(flavortxt.getText());
            cake.setSize(sizetxt.getText());
            cake.setPrice(Double.parseDouble(pricetxt.getText()));

            Registry reg = LocateRegistry.getRegistry("127.0.0.1", 5004);

            CakeService service =
            (CakeService) reg.lookup("cake");

            Cake saved = service.registerCake(cake);

            if(saved != null){
                JOptionPane.showMessageDialog(this, "Cake Saved Successfully");

                displayCakes();   // this makes JTable refresh
                clearFields();

            }else{
                JOptionPane.showMessageDialog(this, "Cake Not Saved");
            }
        }

    }catch(Exception ex){
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
    } 
    }//GEN-LAST:event_savebtnActionPerformed

