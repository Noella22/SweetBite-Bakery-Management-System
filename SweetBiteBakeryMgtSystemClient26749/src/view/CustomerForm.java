    private void savebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebtnActionPerformed
        try{

        if(customeridtxt.getText().isEmpty()
                || fullnametxt.getText().isEmpty()
                || phonetxt.getText().isEmpty()
                || emailtxt.getText().isEmpty()
                || addresstxt.getText().isEmpty()){

            JOptionPane.showMessageDialog(this,
                    "Fill all fields");

        }else{
               //validations
             if(!customeridtxt.getText().matches("[0-9]+")){
        JOptionPane.showMessageDialog(this, "Customer ID must be numbers only");

                       return;
    }

    if(!fullnametxt.getText().matches("[A-Za-z ]+")){
        JOptionPane.showMessageDialog(this,"Full Name must contain letters only");
                
        return;
    }

    if(!phonetxt.getText().matches("[0-9]+")){
        JOptionPane.showMessageDialog(this,"Phone must contain digits only");
                
        return;
    }

    if(phonetxt.getText().length() != 10){
        JOptionPane.showMessageDialog(this,"Phone must be 10 digits");
                
        return;
    }

    if(!emailtxt.getText().contains("@")){
        JOptionPane.showMessageDialog(this,"Invalid Email");
                
        return;
    }

            int customerId =
            Integer.parseInt(customeridtxt.getText());

            String fullname =
            fullnametxt.getText();

            String phone =
            phonetxt.getText();

            String email =
            emailtxt.getText();

            String address =
            addresstxt.getText();

            Registry reg =
            LocateRegistry.getRegistry("127.0.0.1",5004);

            CustomerService service =
            (CustomerService) reg.lookup("customer");

            Customer customer = new Customer();

            customer.setCustomerId(customerId);
            customer.setFullName(fullname);
            customer.setPhone(phone);
            customer.setEmail(email);
            customer.setAddress(address);

            Customer saved =
            service.registerCustomer(customer);

            if(saved != null){

                JOptionPane.showMessageDialog(this,
                        "Customer Saved Successfully");

                displayCustomers();
                clearFields();

            }else{

                JOptionPane.showMessageDialog(this,
                        "Failed");
            }
        }

    }catch(Exception ex){

        ex.printStackTrace();
    }
    }//GEN-LAST:event_savebtnActionPerformed

