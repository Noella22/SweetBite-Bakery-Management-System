        private void displayCustomers(){
                 try{

        Registry reg =
        LocateRegistry.getRegistry("127.0.0.1",5004);

        CustomerService service =
        (CustomerService) reg.lookup("customer");

        List<Customer> customers =
        service.findAllCustomers();

        DefaultTableModel model =
        (DefaultTableModel) customerTable.getModel();

        model.setRowCount(0);

        for(Customer customer : customers){

            Object row[] = {

                customer.getCustomerId(),
                customer.getFullName(),
                customer.getPhone(),
                customer.getEmail(),
                customer.getAddress()
            };

            model.addRow(row);
        }

    }catch(Exception ex){

        ex.printStackTrace();
    }
        } 
        
